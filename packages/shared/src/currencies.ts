const ZERO = new Set(['BIF', 'CLP', 'DJF', 'GNF', 'ISK', 'JPY', 'KMF', 'KRW', 'PYG', 'RWF', 'UGX', 'VND', 'VUV', 'XAF', 'XOF', 'XPF']);
const THREE = new Set(['BHD', 'IQD', 'JOD', 'KWD', 'LYD', 'OMR', 'TND']);

export const CURRENCIES: Currency[] = RAW.map(([code, name, symbol]) => ({
  code,
  name,
  symbol: symbol ?? code,
  digits: ZERO.has(code) ? 0 : THREE.has(code) ? 3 : 2,
}));

const BY_CODE = new Map(CURRENCIES.map((c) => [c.code, c]));
export const CURRENCY_CODES = CURRENCIES.map((c) => c.code) as [string, ...string[]];

export function getCurrency(code: string): Currency {
  const c = BY_CODE.get(code.toUpperCase());
  if (!c) throw new Error(`Unknown currency: ${code}`);
  return c;
}

export const isCurrencyCode = (code: string): boolean => BY_CODE.has(code.toUpperCase());
